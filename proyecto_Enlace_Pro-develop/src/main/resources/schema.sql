-- 1. Creación de la tabla IDIOMAS
CREATE TABLE IDIOMAS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL
);

-- 2. Creación de la tabla ALUMNOS
CREATE TABLE ALUMNOS (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellidos VARCHAR(50),
    email VARCHAR(100) NOT NULL,
    numero_telefono VARCHAR(9),
    fecha_creacion TIMESTAMP NOT NULL,
    direccion VARCHAR(200),
    
    -- Clave foránea hacia IDIOMAS
    idioma_id BIGINT NOT NULL,
    FOREIGN KEY (idioma_id) REFERENCES IDIOMAS(id)
);

-- 3. Secuencias opcionales para generar ids a partir de 20
DROP SEQUENCE IF EXISTS IDIOMAS_SEQ;
CREATE SEQUENCE IDIOMAS_SEQ START WITH 20 INCREMENT BY 1;

DROP SEQUENCE IF EXISTS ALUMNOS_SEQ;
CREATE SEQUENCE ALUMNOS_SEQ START WITH 20 INCREMENT BY 1;
